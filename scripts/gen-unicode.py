"""Generate src/unicode-data.ts from the running CPython.

Usage: python3 scripts/gen-unicode.py > src/unicode-data.ts

The tables pin the behaviour of str.isprintable (used by repr), str.isspace,
int()/float() digit handling and str.lower() to CPython's Unicode database, so
results do not depend on the Unicode version bundled with the JS runtime.
"""
import sys
import unicodedata

MAX = 0x110000


def b36(n):
    if n == 0:
        return "0"
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    out = ""
    while n:
        n, r = divmod(n, 36)
        out = digits[r] + out
    return out


def ranges(cps):
    out = []
    start = prev = None
    for c in cps:
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((start, prev))
            start = prev = c
    if start is not None:
        out.append((start, prev))
    return out


# Non-printable code points as str.isprintable defines them (space is printable).
nonprint = [c for c in range(MAX) if c != 0x20 and not chr(c).isprintable()]
np_enc = []
last_end = 0
for s, e in ranges(nonprint):
    np_enc.append(b36(s - last_end) + "." + b36(e - s))
    last_end = e

zeros = [c for c in range(MAX) if unicodedata.category(chr(c)) == "Nd" and unicodedata.decimal(chr(c)) == 0]
zero_enc = ",".join(b36(z) for z in zeros)

lower_enc = []
last = 0
for c in range(MAX):
    if 0xD800 <= c < 0xE000:
        continue
    lo = chr(c).lower()
    if lo != chr(c):
        lower_enc.append(b36(c - last) + ":" + ".".join(b36(ord(x)) for x in lo))
        last = c

print("// Generated by scripts/gen-unicode.py from CPython %s (Unicode %s). Do not edit." % (
    sys.version.split()[0], unicodedata.unidata_version))
print("export const UNICODE_VERSION = %r;" % unicodedata.unidata_version)
print("export const NONPRINTABLE = %r;" % ",".join(np_enc))
print("export const DIGIT_ZEROS = %r;" % zero_enc)
print("export const LOWER = %r;" % ",".join(lower_enc))
